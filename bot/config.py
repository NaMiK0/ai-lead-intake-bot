# -*- coding: utf-8 -*-
"""
Конфигурация: секреты из окружения, константы, логирование.

Секреты (TELEGRAM_BOT_TOKEN, OPENROUTER_API_KEY) задаются переменными окружения —
см. .env.example в корне репозитория. Ничего секретного в этом файле не хранится.
"""

from __future__ import annotations

import hashlib
import logging
import os
import re

# =============================================================================
#  СЕКРЕТЫ (только из окружения)
# =============================================================================

TELEGRAM_BOT_TOKEN = os.getenv("TELEGRAM_BOT_TOKEN", "").strip()
OPENROUTER_API_KEY = os.getenv("OPENROUTER_API_KEY", "").strip()

# =============================================================================
#  РЕЖИМ ЗАПУСКА (Задача 7: локально — polling, в проде — webhook)
# =============================================================================

# "polling" — локальная разработка (long polling, как раньше, ничего не
# меняется). "webhook" — прод (Render): aiohttp-сервер принимает апдейты по
# HTTP вместо того, чтобы опрашивать Telegram.
BOT_MODE = os.getenv("BOT_MODE", "polling").strip().lower()

# Порт aiohttp-сервера в режиме webhook. Render передаёт свой порт через
# $PORT автоматически — жёстко его не задаём, только дефолт для локальной
# ручной проверки webhook-режима.
PORT = int(os.getenv("PORT", "8080"))

# Публичный базовый URL сервиса (без пути, без слэша на конце), например
# https://lead-bot.onrender.com — нужен только в режиме webhook. На Render
# для веб-сервисов это значение доступно автоматически через
# RENDER_EXTERNAL_URL — если WEBHOOK_URL не задан явно, используем его как
# фолбэк, чтобы не дублировать одно и то же значение руками в двух местах.
WEBHOOK_URL = (
    os.getenv("WEBHOOK_URL", "").strip().rstrip("/")
    or os.getenv("RENDER_EXTERNAL_URL", "").strip().rstrip("/")
)
WEBHOOK_PATH = "/webhook"

# Секрет, которым Telegram подписывает каждый webhook-запрос (заголовок
# X-Telegram-Bot-Api-Secret-Token) — aiogram проверяет его сам. Секрет — не
# часть URL (в отличие от частой практики прятать токен в пути), чтобы не
# оседал в логах/реферерах.
#
# Telegram допускает в secret_token только [A-Za-z0-9_-], 1-256 символов —
# генератор случайных значений Render (generateValue в render.yaml) этого
# не гарантирует и может отдать символы вроде "+"/"/" (проверено вживую:
# "Bad Request: secret token contains illegal characters"). Вместо того
# чтобы полагаться на формат чужого генератора, нормализуем сами: если в
# значении есть недопустимые символы — детерминированно хешируем его в
# hex (только 0-9a-f, точно проходит) вместо использования как есть.
_raw_webhook_secret = os.getenv("WEBHOOK_SECRET", "").strip()
if _raw_webhook_secret and not re.fullmatch(r"[A-Za-z0-9_-]{1,256}", _raw_webhook_secret):
    WEBHOOK_SECRET = hashlib.sha256(_raw_webhook_secret.encode()).hexdigest()
else:
    WEBHOOK_SECRET = _raw_webhook_secret

# =============================================================================
#  БАЗА ДАННЫХ (Postgres)
# =============================================================================

# Локально — Postgres из docker-compose.yml (docker compose up -d postgres),
# в проде — строка подключения от managed-провайдера (например Neon).
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()

# =============================================================================
#  RAG (Qdrant + локальные эмбеддинги)
# =============================================================================

# Рубильник RAG-контура целиком. По умолчанию включён (локальная разработка).
# На Задаче 7 выключен на самом Render: модель эмбеддингов (даже квантованная,
# мультиязычная — единственный вариант в fastembed с поддержкой русского)
# при загрузке реально потребляет ~600 МБ RAM (замерено вживую), что не
# влезает в лимит бесплатного тарифа (512 МБ) и валит процесс OOM ещё до
# того, как успевает дойти до Qdrant. Просто ловить исключение здесь не
# спасает — OOM убивает процесс на уровне ОС, а не кидает перехватываемое
# исключение, поэтому модель не должна даже пытаться загружаться на таком
# хосте. RAG остаётся полностью рабочим и проверенным локально (см. SPEC.md).
RAG_ENABLED = os.getenv("RAG_ENABLED", "true").strip().lower() not in ("false", "0", "no")

# Локально — Qdrant из docker-compose.yml (docker compose up -d qdrant),
# в проде — Qdrant Cloud (URL с API-ключом, ещё не подключено — Задача 7).
QDRANT_URL = os.getenv("QDRANT_URL", "http://localhost:6333").strip()
QDRANT_API_KEY = os.getenv("QDRANT_API_KEY", "").strip() or None

RAG_COLLECTION = "leads"

# fastembed (ONNX через onnxruntime, без torch — легче для деплоя на
# бесплатный тариф). Мультиязычная модель, векторы size=384/cosine —
# проверено вживую на русских формулировках заявок перед выбором
# (см. SPEC.md, Задача 4): парафразы одной темы дают cosine ~0.65-0.69,
# разные темы — ~0.2-0.4.
RAG_MODEL_NAME = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
RAG_VECTOR_SIZE = 384

RAG_TOP_K = 3            # сколько похожих заявок подмешивать в контекст
RAG_SCORE_THRESHOLD = 0.55  # ниже — считаем несвязанным, не показываем модели

# =============================================================================
#  LLM (OpenRouter)
# =============================================================================

OPENROUTER_BASE_URL = "https://openrouter.ai/api/v1"

# Каскад бесплатных моделей. Порядок = приоритет. Список можно править под себя
# (сверить актуальность и поддержку tool calling: GET /api/v1/models,
# поле supported_parameters). Если slug устарел и вернёт ошибку — бот просто
# перейдёт к следующему. openrouter/free — авто-роутер, сам выбирает
# доступную бесплатную модель (страховка на случай, если все конкретные
# slug'и протухли).
MODELS = [
    "nvidia/nemotron-3-super-120b-a12b:free",
    "nvidia/nemotron-3-ultra-550b-a55b:free",
    "openrouter/free",
]

# Таймауты и ретраи для вызова модели
REQUEST_TIMEOUT_S = 45.0        # потолок ожидания ответа модели (не «зависаем»)
ATTEMPTS_PER_MODEL = 2          # попыток на одну модель до перехода к следующей
BACKOFF_BASE_S = 1.5            # база экспоненциальной паузы между ретраями

# =============================================================================
#  ОГРАНИЧЕНИЯ ВХОДА
# =============================================================================

MAX_INPUT_CHARS = 4000          # длинные «простыни» обрезаем, чтобы не жечь токены
MAX_CARDS = 8                   # предохранитель от абсурдного числа карточек

# =============================================================================
#  ДЕДУП (всё в памяти, без диска)
# =============================================================================

SEEN_IDS_MAX = 5000             # LRU-кэш обработанных (chat_id, message_id)
DUP_TTL_S = 3600                # окно, в котором повтор текста считаем дублем
DUP_CACHE_MAX = 2000            # потолок кэша хешей текста

# =============================================================================
#  ДОМЕННЫЕ КОНСТАНТЫ
# =============================================================================

# Допустимые категории (совпадают с тем, что понимает модель по промпту)
CATEGORIES = {"CRM", "сайт", "бот", "автоматизация", "интеграция", "другое"}

